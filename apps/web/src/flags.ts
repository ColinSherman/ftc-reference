/** Lowercase ISO code for `/flags/{code}.svg`, or "" when the country has no flag. */
export function flagCode(country: string | null | undefined): string {
  const iso = country ? ISO[country] : undefined;
  return iso ? iso.toLowerCase() : "";
}
